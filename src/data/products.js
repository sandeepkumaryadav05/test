function product(p) {
  const localImage = productAsset(p.slug)
  return {
    ...p,
    ...(localImage ? { image: localImage } : {}),
    discount: discountPercent(p.price, p.originalPrice),
    weights: p.weights || WEIGHT_PRESETS.halfKg,
    images: localImage ? [localImage] : p.images,
  }
}

