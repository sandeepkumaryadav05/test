export function priceFor(p, weightLabel) {
  const w = (p.weights || []).find((x) => x.label === weightLabel) || (p.weights || [])[0]
  if (!w || w.mult === 1) return p.price
  return Math.round((p.price * w.mult) / 5) * 5
}
